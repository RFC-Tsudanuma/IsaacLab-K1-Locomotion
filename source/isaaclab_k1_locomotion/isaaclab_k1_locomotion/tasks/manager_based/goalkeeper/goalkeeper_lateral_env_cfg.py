        #      eval 跳躍率                      12.84%   16.34% (悪化)
        #
        #    ☆ 機序: **足を水平に保つ最も安い方法は接地しないこと**。空中では地面反力で
        #      足が傾かないので、この項は跳躍を積極的に後押しする。weight 3.0 では
        #      正の報酬の 27% (2.495/9.29) を占める最大項になり、`flight_phase` -2.0 を
        #      入れても跳躍率が上がり続けた (学習中も -0.06 → -0.16 と悪化)。
        #      「水平にすること」が「上げること」の代わりになってしまった。
        #
        #    ★ 遊脚のつま先垂れ自体は依然として実在する問題 (足裏 0.7cm)。直すなら
        #      両足に効く本項ではなく、**遊脚限定** の項 (stance_foot_flat の遊脚版) を
        #      新設すること。接地中しか効かない形なら跳躍への逃げ道が塞がる。

        # 「目標高さの追従」ではなく **「低い高さで水平に流れた距離」** を罰する。
        # 素早く上げて素早く下ろす軌道なら安く満たせる = 07-28 の刻む歩容
        # (名目 0.31s の窓に対し実スイング 0.13〜0.14s) を壊さない。
        # 分子も分母も距離なので **ゆっくり歩いて稼ぐ抜け道が構造的に無い**。
        # ☠ edge_frac=0.3 (急峻ランプ) は必須。線形版は「一番低いところだけ少し上げる」
        #   に収束し、f(10mm) を 0.416 → 0.515 に **悪化** させた (2026-08-17 実測)。
        #   形状報酬のランプは、評価したい指標の指示関数に形を合わせること。
        self.rewards.ground_exposure = RewTerm(
            func=swing_ground_exposure,
            weight=-1.5,
            params={
                "command_name": "base_velocity",
                "h_target": TARGET_GROUND_EXPOSURE_H,
                "edge_frac": 0.3,
                "cmd_threshold": _COMMAND_THRESHOLD,
            },
        )
        # ☠☠ 親の foot_clearance (= foot_clearance_ji、weight 2.5、目標 0.095) を
        #   **消さないこと**。2026-08-17 に消して露出率だけにしたら f(10mm) が
        #   0.321 → 0.498 と 07-28 より悪化した。2 項は要求が違う:
        #       foot_clearance_ji … 「足を上げろ」= スイングに **山を作る** (振幅)
        #       ground_exposure   … 「低いところで流れるな」= **山の形を整える** (形)
        #   形を整える報酬だけ残すと、平べったい軌道のまま形だけ最適化される。
        #   実測 (cmd 1.3、f(10mm)): 07-28 0.321 / 露出率のみ 0.498 / **両方 0.214**。

        # 両足同時浮き = 跳躍を直接罰する。露出率は **跳べば下がる** ので必ずセットで。
        # ☠ lin_vel_z_l2 (-2.5、親の設定) を緩めないこと。「支持脚基準にすれば跳躍は
        #   原理的に塞がる」は誤りで、空中で片脚を畳めば相対高さは稼げる (2026-08-15 実証)。
        self.rewards.flight_phase = RewTerm(func=flight_phase, weight=-2.0)

        # ==================================================================
        # 状態バッファのリセット
        # ==================================================================
        # 実体の更新は報酬側から毎ステップ 1 回だけ呼ばれる (EventTerm の実行順に
        # 依存させない設計)。ここではリセットされた env を無効化するだけ。
        self.events.reset_lateral_buffers = EventTerm(func=reset_lateral_buffers, mode="reset")


