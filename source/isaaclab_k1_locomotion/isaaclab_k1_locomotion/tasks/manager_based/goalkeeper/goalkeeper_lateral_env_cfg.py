# ☠ 経緯のメモ: 3 本目の前に位相を固定 3.5Hz へ上げようとして **取り下げた**。
#   位相を守らせるなら 歩幅 = 速度 / (2×周波数) なので、**周波数を下げるほど要求される
#   歩幅は大きくなる**。当時の横の実測歩幅 0.141m に対し 3.5Hz は 0.186m を要求する値で、
