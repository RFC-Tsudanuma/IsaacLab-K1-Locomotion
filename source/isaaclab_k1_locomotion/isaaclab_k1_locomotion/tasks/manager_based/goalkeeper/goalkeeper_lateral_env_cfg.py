    """全方向で頑健に歩けて、横が速い下位ポリシー。**from scratch で学習する**。"""

    def __post_init__(self):
        super().__post_init__()

        # ==================================================================
        # ★ F. 歩幅の制約 — Hip_Roll の開放は **失敗したので 07-28 に戻した**
        # ==================================================================
        # ☠☠ 3 本目で `joint_deviation_hip` から Hip_Roll を外した (歩幅を伸ばす狙い)。
        #    **便益ゼロ・害あり**だったので 6 本目 (2026-08-21) で戻す。
        #
        #    害: **実機再生で足が外を向いていた** (外股/がに股)。Hip_Roll は脚を左右に
        #        開く関節なので、拘束を外すと開いたまま歩く。導入時に
        #        「外股・がに股に退行する恐れ」と書いていたとおりの副作用。
        #
        #    便益なし: 歩幅はむしろ **拘束のあった 1 本目のほうが大きい**。
        #        1 本目 (拘束あり) 4.76Hz → 0.110m
        #        4 本目 (開放)     3.61Hz → 0.094m
        #        5 本目 (開放)     2.98Hz → 0.093m
        #      ケイデンスが低いほど歩幅は伸びるはずなのに逆転している = 開放の効果はゼロ。
        #      (3 本目の 0.157m は 1.55Hz という低ケイデンスによるもので Hip_Roll ではない)
        #
        #    ★ 歩幅を伸ばす軸は別に移す: `swing_ground_exposure` が高ケイデンス時の歩幅を
        #      抑えている疑い (歩幅を伸ばすほど低クリアランスでの水平移動が増えるため)、
        #      および `min_height` を上げる (骨盤が高いほど同じ外転角で歩幅が出る)。
        # ==================================================================

        # ☆ Hip_Roll の開放は「大きく開いてよい」という **許可** にすぎず、最適点を
        #   動かす **動機** にはならない。許可だけ与えると、空いた自由度を
        #   「同じケイデンスのままもっと速く」に使われて歩幅は変わらない恐れがある。
        #   → 動機側として `feet_air_time` を効かせる。
        #
        #   `feet_air_time_positive_biped` は **単脚支持のときだけ**
        #   min(遊脚の滞空時間, 支持脚の接地時間) を報酬する (0.4s で頭打ち)。
        #     ✓ 長い単脚支持 = **低ケイデンス・大歩幅を直接報酬する**
        #     ✓ **両足浮き (跳躍) は 0 点** (single_stance が偽) → 跳躍率 16.3% にも効く
        #     ✓ 両足接地も 0 点 → だらだら両足で立つのも防ぐ
